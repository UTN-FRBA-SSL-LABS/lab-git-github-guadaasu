#include "operaciones.h"

/* ── sumar ───────────────────────────────────────────────────────────────── */

int sumar(const int a, const int b) {
    return a + b;
}

/* ── restar ──────────────────────────────────────────────────────────────── */

int restar(int a, int b) {
    return a - b;
}

/* ── multiplicar ─────────────────────────────────────────────────────────── */

// Esta funcion multiplica dos enteros
int multiplicar(int a, int b) {
    return a * b;
}

/* ── esPar ───────────────────────────────────────────────────────────────── */

int esPar(int n) {
    return (n % 2) == 0;
}
